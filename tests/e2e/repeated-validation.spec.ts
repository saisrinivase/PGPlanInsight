import { expect, test } from "@playwright/test";
const capture = (time: number, reads = 100) => JSON.stringify({ Plan: { "Node Type": "Seq Scan", "Relation Name": "synthetic_orders", "Actual Total Time": time, "Actual Loops": 1, "Actual Rows": 10, "Plan Rows": 10, "Shared Read Blocks": reads, "Temp Written Blocks": 0, "WAL Bytes": 0 }, "Execution Time": time, Settings: { work_mem: "4MB" } });
const files = (times: number[], reads = 100) => times.map((time, index) => ({ name: `synthetic-run-${index}.json`, mimeType: "application/json", buffer: Buffer.from(capture(time, reads)) }));

test("repeated captures compare medians, export all runs and block resource regressions", async ({ page }) => {
  await page.goto("/");
  await page.getByLabel("Plan evidence").fill(capture(100));
  await page.getByRole("button", { name: /Analyze plan/ }).click();
  await page.getByRole("button", { name: "Validate fix", exact: true }).click();
  const workbench = page.locator(".validation-workbench");
  for (const box of await workbench.getByRole("checkbox").all()) await box.check();
  await page.getByLabel("After plan evidence").fill(capture(40));
  await page.getByLabel("Additional before captures").setInputFiles(files([110, 120]));
  await expect(workbench.getByText("Before captures: 3", { exact: true })).toBeVisible();
  await page.getByLabel("Additional after captures").setInputFiles(files([50, 60]));
  await expect(workbench.getByText("After captures: 3", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Run comparison gate" }).click();
  await expect(page.getByRole("region", { name: "Validation verdict" })).toContainText("Improved");
  const evidence = page.getByRole("region", { name: "Repeated runtime evidence" });
  await expect(evidence).toContainText("110");
  await expect(evidence).toContainText("50");
  await evidence.getByText("Individual runtimes and interpretation", { exact: true }).click();
  await expect(evidence).toContainText("100 ms, 110 ms, 120 ms");
  await expect(evidence).toContainText("production-wide benefit remain unknown");
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export validation report" }).click();
  const report = await download;
  const stream = await report.createReadStream();
  let text = ""; for await (const chunk of stream!) text += chunk.toString();
  expect(text).toContain("Runs (ms): 100, 110, 120");
  expect(text).toContain("not statistical confidence");
  await page.getByLabel("Additional after captures").setInputFiles(files([50, 60], 400));
  await expect(page.getByRole("button", { name: "Run comparison gate" })).toBeEnabled();
  await page.getByRole("button", { name: "Run comparison gate" }).click();
  await expect(page.getByRole("region", { name: "Validation verdict" })).toContainText("Inconclusive");
  await expect(workbench).toContainText("Median resource use increased");
  await page.getByRole("button", { name: "Clear additional captures" }).click();
  await expect(workbench.getByText("Before captures: 1", { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width);
});
